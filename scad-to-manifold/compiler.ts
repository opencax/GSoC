import { 
    type ASTVisitor, type ScadFile, type ModuleInstantiationStmt, type LiteralExpr, 
    type VectorExpr, type BinaryOpExpr, type UnaryOpExpr, type AssignmentNode,
    type GroupingExpr, type TernaryExpr, type FunctionCallExpr, LookupExpr,
    type IfElseStatement, type BlockStmt, type ErrorNode, type NoopStmt,
    type RangeExpr, type ArrayLookupExpr, type ModuleDeclarationStmt,
    type FunctionDeclarationStmt, type MemberLookupExpr, type LetExpr,
    type AssertExpr, type EchoExpr, type LcIfExpr, type LcEachExpr,
    type LcForExpr, type LcForCExpr, type LcLetExpr, type AnonymousFunctionExpr,
    type UseStmt, type IncludeStmt
} from 'openscad-parser';

export enum AssignmentNodeRole {
    VARIABLE_DECLARATION = 0,
    ARGUMENT_DECLARATION = 1,
    ARGUMENT_ASSIGNMENT = 2
}

export class OpenScadCompiler implements ASTVisitor<string> {
    private indentLevel: number = 0;
    private resultsStack: string[] = ['results'];
    private declarations: string = '';

    constructor() {}

    private indent(): string {
        return '    '.repeat(this.indentLevel);
    }

    private get currentResults(): string {
        return this.resultsStack[this.resultsStack.length - 1]!;
    }

    compile(ast: ScadFile): string {
        this.declarations = '';
        this.indentLevel = 0;
        
        let mainBody = this.visitScadFile(ast);

        let code = `// Automatically generated by OpenSCAD-to-Manifold Compiler\n`;
        code += `import { Mesh } from 'manifold-3d';\n\n`;
        
        // Runtime helpers
        code += this.getRuntimeHelpers();
        
        // Declarations (modules and functions)
        code += this.declarations;
        
        code += `export async function main() {\n`;
        this.indentLevel = 1;
        code += `${this.indent()}let scope = new RuntimeScope();\n`;
        code += `${this.indent()}let results = [];\n`;
        
        code += mainBody;
        
        code += `${this.indent()}return results;\n`;
        code += `}\n`;
        return code;
    }

    private getRuntimeHelpers(): string {
        return `
class RuntimeScope {
    constructor(parent = null) {
        this.parent = parent;
        this.variables = {};
        this.modules = {};
        this.functions = {};
    }
    set(name, value) { this.variables[name] = value; }
    get(name) {
        if (this.variables[name] !== undefined) return this.variables[name];
        return this.parent ? this.parent.get(name) : undefined;
    }
    setModule(name, fn) { this.modules[name] = fn; }
    getModule(name) {
        if (this.modules[name] !== undefined) return this.modules[name];
        return this.parent ? this.parent.getModule(name) : undefined;
    }
    setFunction(name, fn) { this.functions[name] = fn; }
    getFunction(name) {
        if (this.functions[name] !== undefined) return this.functions[name];
        return this.parent ? this.parent.getFunction(name) : undefined;
    }
}

function range(begin, step, end) {
    if (end === undefined) { end = step; step = 1; }
    let res = [];
    if (step === 0) return [];
    for (let i = begin; step > 0 ? i <= end : i >= end; i += step) {
        res.push(i);
    }
    return res;
}

function setVariablesFromArgs(scope, argNames, positionalArgs, namedArgs) {
    argNames.forEach((name, i) => {
        if (positionalArgs[i] !== undefined) scope.set(name, positionalArgs[i]);
    });
    Object.entries(namedArgs).forEach(([name, val]) => {
        scope.set(name, val);
    });
}
\n`;
    }

    visitScadFile(n: ScadFile): string {
        return n.statements.map(s => s.accept(this)).join('');
    }

    visitModuleInstantiationStmt(n: ModuleInstantiationStmt): string {
        const name = n.name;
        
        if (name === 'for' && n.child) {
            const arg = n.args[0];
            if (!arg || !arg.name) return `${this.indent()}// Invalid for loop\n`;
            
            const loopVar = arg.name;
            const loopRange = arg.value ? arg.value.accept(this) : '[]';
            
            let out = `${this.indent()}for (let val of ${loopRange}) {\n`;
            this.indentLevel++;
            out += `${this.indent()}scope.set("${loopVar}", val);\n`;
            out += n.child.accept(this);
            this.indentLevel--;
            out += `${this.indent()}}\n`;
            return out;
        }

        let positionalArgs: string[] = [];
        let namedArgs: string[] = [];
        
        for (const arg of n.args) {
            const val = arg.value ? arg.value.accept(this) : 'null';
            if (arg.name) {
                 namedArgs.push(`${arg.name}: ${val}`);
            } else {
                 positionalArgs.push(val);
            }
        }
        
        let argsStr = positionalArgs.join(', ');
        let namedObjStr = namedArgs.length > 0 ? `{ ${namedArgs.join(', ')} }` : '{}';
        
        // Built-ins
        switch (name) {
            case 'translate':
            case 'rotate':
            case 'scale':
            case 'union':
            case 'difference':
            case 'intersection':
            case 'cube':
            case 'sphere':
            case 'cylinder':
                {
                    const manifoldArgs = positionalArgs.join(', ') + (namedArgs.length > 0 ? (positionalArgs.length > 0 ? ', ' : '') + `{ ${namedArgs.join(', ')} }` : '');
                    let out = '';
                    const isLeaf = !n.child || (n.child.constructor.name === 'NoopStmt');
                    if (!isLeaf && n.child) {
                        out += `${this.indent()}{\n`;
                        this.indentLevel++;
                        out += `${this.indent()}let subResults = [];\n`;
                        this.resultsStack.push('subResults');
                        out += n.child.accept(this);
                        this.resultsStack.pop();
                        
                        if (['translate', 'rotate', 'scale'].includes(name)) {
                            out += `${this.indent()}${this.currentResults}.push(...subResults.map(m => m.${name}(${manifoldArgs})));\n`;
                        } else if (name === 'union') {
                            out += `${this.indent()}${this.currentResults}.push(Mesh.union(subResults));\n`;
                        } else if (name === 'difference' || name === 'intersection') {
                            out += `${this.indent()}if (subResults.length > 0) {\n`;
                            out += `${this.indent()}    let base = subResults[0];\n`;
                            out += `${this.indent()}    for (let i = 1; i < subResults.length; i++) base = Mesh.${name}(base, subResults[i]);\n`;
                            out += `${this.indent()}    ${this.currentResults}.push(base);\n`;
                            out += `${this.indent()}}\n`;
                        }
                        this.indentLevel--;
                        out += `${this.indent()}}\n`;
                    } else {
                        out = `${this.indent()}${this.currentResults}.push(Mesh.${name}(${manifoldArgs}));\n`;
                    }
                    return out;
                }
        }

        // Custom Modules
        const childrenCallback = n.child && n.child.constructor.name !== 'NoopStmt' 
            ? `async (scope) => {\n        let results = [];\n        ${n.child.accept(this).replace(/\n/g, '\n        ')}\n        return results;\n    }` 
            : 'null';
            
        return `${this.indent()}${this.currentResults}.push(...await scope.getModule("${name}")(scope, [${positionalArgs.join(', ')}], ${namedObjStr}, ${childrenCallback}));\n`;
    }

    visitAssignmentNode(n: AssignmentNode): string {
        const name = n.name;
        const val = n.value ? n.value.accept(this) : 'null';
        if ((n as any).role === 2) {
            return name ? `${name}: ${val}` : val;
        }
        return `${this.indent()}scope.set("${name}", ${val});\n`;
    }

    visitLiteralExpr(n: LiteralExpr<any>): string {
        const val = n.value;
        if (typeof val === 'string') return `"${val}"`;
        return val.toString();
    }

    visitVectorExpr(n: VectorExpr): string {
        return `[${n.children.map(e => e.accept(this)).join(', ')}]`;
    }

    visitLookupExpr(n: LookupExpr): string {
        // Check if it's a function or variable
        return `scope.get("${n.name}")`;
    }

    visitBinaryOpExpr(n: BinaryOpExpr): string {
        const left = n.left.accept(this);
        const right = n.right.accept(this);
        const op = n.tokens.operator.lexeme;
        return `(${left} ${op} ${right})`;
    }

    visitUnaryOpExpr(n: UnaryOpExpr): string {
        const right = n.right.accept(this);
        const op = n.tokens.operator.lexeme;
        return `(${op}${right})`;
    }

    visitBlockStmt(n: BlockStmt): string {
        return n.children.map(s => s.accept(this)).join('');
    }

    visitIfElseStatement(n: IfElseStatement): string {
        const cond = n.cond.accept(this);
        let out = `${this.indent()}if (${cond}) {\n`;
        this.indentLevel++;
        out += n.thenBranch.accept(this);
        this.indentLevel--;
        out += `${this.indent()}}\n`;
        if (n.elseBranch) {
            out += `${this.indent()}else {\n`;
            this.indentLevel++;
            out += n.elseBranch.accept(this);
            this.indentLevel--;
            out += `${this.indent()}}\n`;
        }
        return out;
    }

    visitGroupingExpr(n: GroupingExpr): string {
        return `(${n.inner.accept(this)})`;
    }

    visitFunctionCallExpr(n: FunctionCallExpr): string {
        const name = n.callee instanceof LookupExpr ? (n.callee as LookupExpr).name : null;
        const argsStr = n.args.map(a => a.accept(this)).join(', ');
        
        if (name && ['sin', 'cos', 'tan', 'sqrt', 'abs', 'round', 'ceil', 'floor'].includes(name)) {
            return `Math.${name}(${argsStr})`;
        }
        
        const callee = n.callee.accept(this);
        return `${callee}(${argsStr})`;
    }

    visitRangeExpr(n: RangeExpr): string {
        const begin = n.begin.accept(this);
        const end = n.end.accept(this);
        const step = n.step ? n.step.accept(this) : '1';
        return `range(${begin}, ${step}, ${end})`;
    }

    visitArrayLookupExpr(n: ArrayLookupExpr): string {
        const array = n.array.accept(this);
        const index = n.index.accept(this);
        return `${array}[${index}]`;
    }

    visitModuleDeclarationStmt(n: ModuleDeclarationStmt): string {
        const name = n.name;
        const argNames = n.definitionArgs.map(a => `"${a.name}"`).join(', ');
        const savedIndent = this.indentLevel;
        this.indentLevel = 1;

        let moduleCode = `async function module_${name}(parentScope, positionalArgs, namedArgs, children) {\n`;
        moduleCode += `    let scope = new RuntimeScope(parentScope);\n`;
        // Handle default values for definition args if any
        n.definitionArgs.forEach(arg => {
            if (arg.value) {
                moduleCode += `    scope.set("${arg.name}", ${arg.value.accept(this)});\n`;
            }
        });
        moduleCode += `    setVariablesFromArgs(scope, [${argNames}], positionalArgs, namedArgs);\n`;
        moduleCode += `    let results = [];\n`;
        this.resultsStack.push('results');
        moduleCode += n.stmt.accept(this).replace(/\n/g, '\n    ');
        this.resultsStack.pop();
        moduleCode += `    return results;\n`;
        moduleCode += `}\n\n`;
        
        this.declarations += moduleCode;
        this.indentLevel = savedIndent;
        
        return `${this.indent()}scope.setModule("${name}", module_${name});\n`;
    }

    visitFunctionDeclarationStmt(n: FunctionDeclarationStmt): string {
        const name = n.name;
        const argNames = n.definitionArgs.map(a => a.name).join(', ');
        const expr = n.expr.accept(this);
        
        let fnCode = `function fn_${name}(${argNames}) {\n    return ${expr};\n}\n\n`;
        this.declarations += fnCode;
        
        return `${this.indent()}scope.set("${name}", fn_${name});\n`;
    }

    visitTernaryExpr(n: TernaryExpr): string {
        return `(${n.cond.accept(this)} ? ${n.ifExpr.accept(this)} : ${n.elseExpr.accept(this)})`;
    }

    visitMemberLookupExpr(n: MemberLookupExpr): string {
        return `${n.expr.accept(this)}.${n.member}`;
    }

    visitLetExpr(n: LetExpr): string {
        let out = `((() => {\n`;
        this.indentLevel++;
        n.args.forEach(arg => {
            out += `${this.indent()}let ${arg.name} = ${arg.value ? arg.value.accept(this) : 'null'};\n`;
        });
        out += `${this.indent()}return ${n.expr.accept(this)};\n`;
        this.indentLevel--;
        out += `${this.indent()}})())`;
        return out;
    }

    visitAssertExpr(n: AssertExpr): string {
        return `((() => { if (!(${n.args[0]?.value?.accept(this)})) console.assert(false, "Assertion failed"); return ${n.expr.accept(this)}; })())`;
    }

    visitEchoExpr(n: EchoExpr): string {
        const argsStr = n.args.map(a => a.accept(this)).join(', ');
        return `((() => { console.log("ECHO:", ${argsStr}); return ${n.expr.accept(this)}; })())`;
    }

    visitLcIfExpr(n: LcIfExpr): string {
        return `(${n.cond.accept(this)} ? [${n.ifExpr.accept(this)}] : [${n.elseExpr ? n.elseExpr.accept(this) : ''}])`;
    }

    visitLcEachExpr(n: LcEachExpr): string {
        return `[...${n.expr.accept(this)}]`;
    }

    visitLcForExpr(n: LcForExpr): string {
        const arg = n.args[0];
        if (!arg || !arg.name) return '[]';
        return `[].concat(...${arg.value?.accept(this)}.map(${arg.name} => ${n.expr.accept(this)}))`;
    }

    visitLcForCExpr(n: LcForCExpr): string { return '[]'; }
    visitLcLetExpr(n: LcLetExpr): string { return '[]'; }

    visitAnonymousFunctionExpr(n: AnonymousFunctionExpr): string {
        const args = n.definitionArgs.map(a => a.name).join(', ');
        return `((${args}) => ${n.expr.accept(this)})`;
    }

    visitUseStmt(n: UseStmt): string { return `${this.indent()}// use <${n.filename}>\n`; }
    visitIncludeStmt(n: IncludeStmt): string { return `${this.indent()}// include <${n.filename}>\n`; }
    visitNoopStmt(n: NoopStmt): string { return ''; }
    visitErrorNode(n: ErrorNode): string { return `${this.indent()}// Parsing error encountered\n`; }
}




